import postcss from '../src-ui/node_modules/postcss/lib/postcss.mjs';
import tailwindcss from '../src-ui/node_modules/tailwindcss/lib/index.js';
import tailwindConfig from '../src-ui/tailwind.config.js';
import { build } from '../src-ui/node_modules/esbuild/lib/main.js';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root, entryPoints: ['src-ui/src/ai/webui/client.tsx'], bundle: true, write: false,
  format: 'cjs', platform: 'browser', jsx: 'automatic', external: ['react', 'react/jsx-runtime'],
  minify: false, target: 'es2022',
});
const baseCss = await readFile(new URL('../src-ui/src/ai/webui/style.css', import.meta.url), 'utf8');
const utilities = await postcss([tailwindcss({ ...tailwindConfig, important: '.lamber-business', corePlugins: { preflight: false }, content: [root + 'src-ui/src/components/ai/*.tsx', root + 'src-ui/src/ai/webui/*.tsx'] })]).process('@tailwind utilities;', { from: undefined });
const css = baseCss + utilities.css;
await writeFile(new URL('../agent-bridge/webui/lamber-brand/lib/client.js', import.meta.url),
  `// Generated by scripts/build-webui-client.mjs; edit src-ui/src/ai/webui.\nwindow.__ModuleLoader__.load({id:'dsh-client-ui-lamber-brand',factory(require){\nconst module={exports:{}};\n${result.outputFiles[0].text}\nconst css=${JSON.stringify(css)};\nreturn {...module.exports,apply(ctx){ctx.effect(()=>{const style=document.createElement('style');style.textContent=css;document.head.append(style);return ()=>style.remove();});return module.exports.apply(ctx);}};}});\n`);

await build({ absWorkingDir: root, entryPoints: ['src-ui/src/ai/webui/businessPresentation.ts'], bundle: true,
  format: 'esm', platform: 'node', target: 'node22', outfile: 'agent-bridge/webui/lamber-host/business-presentation.generated.js' });
